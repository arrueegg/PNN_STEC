# --- #10: the storm/quiet definition -----------------------------------------------------


def _measure_storm_definition() -> Effect:
    """Count storm days under both rules over the real OMNI archive (full 2024, 366 days,
    independent of positioning coverage), and, where the positioning summary is on disk,
    the quiet/storm improvement over IGS GIM under each rule (reusing
    `stec.analysis.storm_stratification`'s building blocks, not its fixed threshold)."""
    from ..positioning import metrics as pm
    from . import storm_stratification as ss

    if not paths.OMNI_INDICES.exists():
        return _STORM_DEFINITION_EFFECT

    indices = ss.load_daily_geomagnetic_indices(2024, paths.OMNI_INDICES)
    daily_storm = classify_storm_days_daily(indices["dst_min"])
    combined_storm = classify_storm_days_combined(indices["dst_min"], indices["kp_max"])
    measurements = [
        Measurement(
            "storm days, full 2024 OMNI archive, daily Dst<=-50 nT",
            new_value=int(daily_storm.sum()),
            unit="days",
            n=len(indices),
        ),
        Measurement(
            "storm days, full 2024 OMNI archive, combined Kp>=37 or Dst<=-33",
            new_value=int(combined_storm.sum()),
            unit="days",
            n=len(indices),
        ),
    ]

    summary_path = ss.canonical_positioning_summary()
    if summary_path.exists():
        positions = pd.read_csv(summary_path)
        merged = positions.merge(indices, on="doy", how="left").dropna(
            subset=["dst_min"]
        )
        merged = pm.exclude_outlier_station_days(merged)
        merged["Method"] = (
            merged["method"].map(ss.METHOD_LABELS).fillna(merged["method"])
        )

        for rule_name, is_storm in (
            ("daily Dst<=-50", classify_storm_days_daily(merged["dst_min"])),
            (
                "combined Kp>=37 or Dst<=-33",
                classify_storm_days_combined(merged["dst_min"], merged["kp_max"]),
            ),
        ):
            regime = merged.assign(regime=np.where(is_storm, "storm", "quiet"))
            by_regime = pm.summarise(regime, ["Method", "regime"])
            means = by_regime["3D_mean_m"].unstack("regime")
            baseline = means.loc[ss.GIM_LABEL]
            gain = 100 * (baseline - means.loc["Direct STEC"]) / baseline
            measurements.append(
                Measurement(
                    f"Direct STEC improvement over IGS GIM, quiet, {rule_name}",
                    new_value=round(float(gain["quiet"]), 3),
                    unit="%",
                )
            )
            measurements.append(
                Measurement(
                    f"Direct STEC improvement over IGS GIM, storm, {rule_name}",
                    new_value=round(float(gain["storm"]), 3),
                    unit="%",
                )
            )

    return MeasuredEffect(
        method=(
            "Applied both rules to the daily Dst_min/Kp_max extremes read from "
            "data/omni_hourly_2010-2025.h5, then joined to the positioning summary "
            "(exclude_outlier_station_days applied first) to get the improvement under "
            "each rule."
        ),
        measurements=tuple(measurements),
    )


