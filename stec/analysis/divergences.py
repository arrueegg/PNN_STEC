# --- #9: the 10 m outlier boundary ------------------------------------------------------


def _measure_outlier_boundary() -> Effect:
    """Count real station-days at exactly the 10.0 m boundary across the three source
    trees `stec.analysis.common_set_positioning` reads: the published three-way tree, the
    weighting ablation, and the pretrained elevation arm's per-day summaries."""
    from .common_set_positioning import (
        ARM_LABELS,
        COLUMNS,
        DEFAULT_EXPERIMENT,
        load_pretrained_elev,
    )
    from .positioning_summary import (
        DEFAULT_WEIGHTING_SUMMARY,
        canonical_positioning_summary,
    )

    sources = {
        "three_way": canonical_positioning_summary(),
        "ablation": DEFAULT_WEIGHTING_SUMMARY,
    }
    total_rows = 0
    total_boundary = 0
    for path in sources.values():
        if not path.exists():
            return _OUTLIER_BOUNDARY_EFFECT
        frame = pd.read_csv(path, usecols=lambda c: c in COLUMNS)
        frame = frame[frame["method"].isin(ARM_LABELS)]
        total_rows += len(frame)
        total_boundary += count_boundary_rows(frame["error_3d_rms"])

    elev = load_pretrained_elev(DEFAULT_EXPERIMENT)
    total_rows += len(elev)
    if len(elev):
        total_boundary += count_boundary_rows(elev["error_3d_rms"])

    return MeasuredEffect(
        method=(
            "Counted error_3d_rms == 10.0 across positioning_comparison_3way, "
            "positioning_20260216_2052 and the pretrained-elevation per-day summaries - "
            "the same three trees stec.analysis.common_set_positioning reads."
        ),
        measurements=(
            Measurement(
                "station-day rows at exactly 10.000 m (move between `<` and `<=`)",
                new_value=total_boundary,
                unit="rows",
                n=total_rows,
            ),
        ),
    )


