def by_id(id_: str) -> Divergence:
    for divergence in REGISTRY:
        if divergence.id == id_:
            return divergence
    raise KeyError(f"no divergence registered with id {id_!r}")


def _check_unique_ids(registry: tuple[Divergence, ...] = REGISTRY) -> None:
    seen: set[str] = set()
    for divergence in registry:
        if divergence.id in seen:
            raise ValueError(f"duplicate divergence id {divergence.id!r}")
        seen.add(divergence.id)


_check_unique_ids()


