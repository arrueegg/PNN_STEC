# --- pure measurement functions -----------------------------------------------------
#
# Each one is small enough to hand-verify and carries no I/O, which is what makes it
# testable against a synthetic input with a hand-computed answer.


def doy_lookup_disagrees(doy: int, total_days: int = 365) -> bool:
    """Reproduce the float32 round-trip that corrupted the GIM day lookup (defect #1).

    `doy` was normalised to `(doy - 1) / total_days` for the model input and inverted in
    float32 when read back from a results frame (`stec/baselines/gim.py`,
    `date_from_year_doy`). Float32 rounding sometimes lands the inverted value just under
    the intended integer (e.g. DOY 189 comes back as 188.99998), so `int()` truncates to
    the *previous* day while `round()` recovers the correct one. Returns whether the two
    disagree for the given `doy`.
    """
    denormalised = _denormalised_doy(doy, total_days)
    return int(denormalised) != round(denormalised)


def _denormalised_doy(doy: int, total_days: int = 365) -> float:
    """The exact float32 forward-then-inverse transform the model input goes through."""
    normalised = np.float32((doy - 1) / total_days)
    return float(normalised * np.float32(total_days) + np.float32(1))


def count_boundary_rows(values: Sequence[float], threshold: float = 10.0) -> int:
    """Count station-days sitting exactly at `threshold` (defect #9).

    These are the only rows that move between a strict `<` (excluded) and a `<=`
    (included) outlier rule - anything not exactly equal to the threshold is treated
    identically by both operators.
    """
    array = np.asarray(values, dtype=float)
    return int(np.count_nonzero(array == threshold))


def classify_storm_days_daily(
    dst_min: pd.Series, threshold: float = -50.0
) -> pd.Series:
    """The positioning (R2.7) storm rule: a day is a storm when its daily minimum Dst
    reaches `threshold` nT."""
    return dst_min <= threshold


def classify_storm_days_combined(
    dst_min: pd.Series,
    kp_max: pd.Series,
    kp_threshold: float = 37.0,
    dst_threshold: float = -33.0,
) -> pd.Series:
    """The per-observation (STEC scenario) storm rule, applied at the day level by taking
    each day's extremes: a day is a storm when its daily max Kp or min Dst crosses the
    threshold. Kp is stored scaled by 10 in the OMNI archive (37 means Kp 3.7)."""
    return (kp_max >= kp_threshold) | (dst_min <= dst_threshold)


def interval_coverage(
    y: np.ndarray, mu: np.ndarray, sigma: np.ndarray, level: float, family: str
) -> float:
    """Empirical fraction of observations inside the central `level` interval under a
    Gaussian or Laplace predictive with the given mean and standard deviation `sigma`
    (defect #4 is scoring a Laplace-trained model's uncertainty as if it were Gaussian).

    Mirrors `stec.analysis.uncertainty_calibration.half_width`, reimplemented here as a
    small standalone function - importing that module's version would work equally well,
    but this keeps the divergence measurable without depending on its streaming
    accumulator machinery for what is, at its core, one closed-form formula.
    """
    if family == "laplace":
        scale = sigma / np.sqrt(2.0)
        half_width = -scale * np.log(1.0 - level)
    elif family == "gaussian":
        from scipy.stats import norm

        half_width = sigma * norm.ppf(0.5 + level / 2)
    else:
        raise ValueError(f"unknown predictive family {family!r}")
    return float(np.mean(np.abs(y - mu) <= half_width))


# --- effect types ---------------------------------------------------------------------


@dataclass(frozen=True)
class Measurement:
    """One reported number: what changed, from what value to what value."""

    label: str
    new_value: float
    unit: str
    old_value: float | None = None  # None when there is no single prior number to cite
    n: int | None = None  # sample size this was measured over, when that is meaningful


@dataclass(frozen=True)
class MeasuredEffect:
    """The quantified outcome of running a divergence's measurement, real numbers from a
    real (read-only) source, tagged with how they were obtained."""

    method: str  # one line: what was read or computed, and from where
    measurements: tuple[Measurement, ...]

    def __post_init__(self) -> None:
        if not self.measurements:
            raise ValueError("a MeasuredEffect must carry at least one Measurement")


@dataclass(frozen=True)
class UnmeasurableEffect:
    """Why this divergence's effect cannot be quantified right now, and what would make
    it quantifiable. Carries no number on purpose - a placeholder number here is exactly
    the fabrication this registry exists to prevent."""

    reason: str
    would_require: str


Effect = MeasuredEffect | UnmeasurableEffect

ApplicationStatus = Literal["applied", "available_but_off", "not_yet_ported"]
EffectStatus = Literal["measured", "unmeasurable_now"]


@dataclass(frozen=True)
class Divergence:
    """One named, deliberate source of divergence between the rebuilt pipeline and the
    submitted paper.

    `applied` and the derived `status` answer two different questions. `applied` is about
    the *code*: does the rebuilt pipeline's default path already produce the changed
    behaviour, does the fix exist only as an opt-in the default path does not take, or
    has nothing been ported yet. `status` is about *this registry*: did measuring the
    effect right now, read-only, produce a number, or not.
    """

    id: str
    description: str
    deliverable: str
    reviewer_comment: str | None
    applied: ApplicationStatus
    recorded_effect: Effect
    measure: Callable[[], Effect]

    def __post_init__(self) -> None:
        if not self.id:
            raise ValueError("a divergence must have a non-empty id")
        if not self.description:
            raise ValueError(f"{self.id}: description must not be empty")
        if not self.deliverable:
            raise ValueError(f"{self.id}: deliverable must not be empty")
        if isinstance(self.recorded_effect, MeasuredEffect):
            for m in self.recorded_effect.measurements:
                if m.new_value is None:
                    raise ValueError(
                        f"{self.id}: measured effect '{m.label}' carries no numeric value"
                    )
        elif isinstance(self.recorded_effect, UnmeasurableEffect):
            if (
                not self.recorded_effect.reason
                or not self.recorded_effect.would_require
            ):
                raise ValueError(
                    f"{self.id}: unmeasurable effect must carry both a reason and what "
                    "measuring it would require"
                )
        else:
            raise TypeError(
                f"{self.id}: unrecognised effect type {type(self.recorded_effect)}"
            )

    @property
    def status(self) -> EffectStatus:
        return (
            "measured"
            if isinstance(self.recorded_effect, MeasuredEffect)
            else "unmeasurable_now"
        )


def _unmeasurable(reason: str, would_require: str) -> UnmeasurableEffect:
    return UnmeasurableEffect(reason=reason, would_require=would_require)


